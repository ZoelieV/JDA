-- Feedbacks des joueurs (à lancer une fois dans Supabase : SQL Editor > New
-- query > Run). Sans risque si relancé.
--
-- Tout joueur connecté peut envoyer un feedback depuis l'accueil (bouton en
-- bas à gauche) : 1000 caractères au plus, sans lien, un par jour (reset à 4 h)
-- (cf. api/_lib/feedbacks.js). Lu par les administrateurs et mini admins
-- dans la page Administration (bouton Feedback) ; les administrateurs le
-- classent ou le suppriment :
--   statut : 'nouveau' (à lire), 'pris_en_compte' ou 'termine'
--   traite_par / traite_le : administrateur qui a changé le statut
create table if not exists feedbacks (
  id bigint generated by default as identity primary key,
  discord_id text not null,
  -- Pseudo au moment de l'envoi (le pseudo actuel est relu dans profiles).
  nom text,
  texte text not null check (char_length(texte) <= 1000),
  statut text not null default 'nouveau' check (statut in ('nouveau', 'pris_en_compte', 'termine')),
  traite_par text,
  traite_le timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists feedbacks_joueur on feedbacks (discord_id, created_at desc);
create index if not exists feedbacks_date on feedbacks (created_at desc);

-- Fermée à l'accès public (le site passe par la clé de service).
alter table feedbacks enable row level security;
