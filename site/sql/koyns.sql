-- Koyns : monnaie du site (gagnée en jouant, jamais achetable), cf.
-- api/_lib/koyns.js. À lancer une fois dans Supabase : SQL Editor > New
-- query > Run. Sans risque si relancé.
--
-- Tables lues et écrites par la clé de service seulement (RLS sans
-- politique, aucun droit pour anon / authenticated, cf. revoke_anon.sql).

-- 1. Mouvements : un gain (match, bonus, départ, don d'un admin) ou une
-- dépense (achat), en positif ou négatif. Le solde est leur somme.
-- ref : identifiant unique par joueur (match:<id>, achat:<cosmétique>,
-- depart, connexion:<jour>...) : jamais deux fois le même gain.
-- adversaires : joueurs affrontés (ids triés), pour le plafond de games
-- récompensées par jour contre les mêmes adversaires.
create table if not exists koyns_mouvements (
  id bigint generated by default as identity primary key,
  discord_id text not null,
  montant integer not null,
  raison text not null,
  ref text not null,
  adversaires text,
  cree_le timestamptz not null default now(),
  unique (discord_id, ref)
);
create index if not exists koyns_mouvements_joueur on koyns_mouvements (discord_id, cree_le);
alter table koyns_mouvements enable row level security;

-- 2. Cosmétiques possédés (achetés, offerts par un admin, récompenses
-- d'événement). Ids : "fond:<id>", "banniere:<chemin>", "skin:<id>"...
create table if not exists cosmetiques_possedes (
  discord_id text not null,
  cosmetique text not null,
  source text not null default 'achat',
  obtenu_le timestamptz not null default now(),
  primary key (discord_id, cosmetique)
);
alter table cosmetiques_possedes enable row level security;

-- 3. Achat atomique : verrou par joueur (deux achats simultanés ne
-- dépensent pas deux fois le même solde), puis vérifications et écritures.
-- -> 'ok', 'deja' (déjà possédé) ou 'solde' (pas assez de Koyns).
create or replace function acheter_cosmetique(p_discord_id text, p_cosmetique text, p_prix integer)
returns text
language plpgsql
set search_path = public
as $$
begin
  perform pg_advisory_xact_lock(hashtext('koyns:' || p_discord_id));
  if exists (select 1 from cosmetiques_possedes where discord_id = p_discord_id and cosmetique = p_cosmetique) then
    return 'deja';
  end if;
  if coalesce((select sum(montant) from koyns_mouvements where discord_id = p_discord_id), 0) < p_prix then
    return 'solde';
  end if;
  insert into koyns_mouvements (discord_id, montant, raison, ref)
    values (p_discord_id, -p_prix, 'achat', 'achat:' || p_cosmetique);
  insert into cosmetiques_possedes (discord_id, cosmetique, source)
    values (p_discord_id, p_cosmetique, 'achat');
  return 'ok';
end;
$$;

revoke all on function acheter_cosmetique(text, text, integer) from public, anon, authenticated;
grant execute on function acheter_cosmetique(text, text, integer) to service_role;

-- 4. Vérification : les deux tables existent, RLS activé.
select tablename, rowsecurity from pg_tables
where schemaname = 'public' and tablename in ('koyns_mouvements', 'cosmetiques_possedes');
